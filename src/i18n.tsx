export type TranslationKey = keyof typeof en
export type Translate = (key: TranslationKey, values?: Record<string, string | number>) => string
type I18nContextValue = { language: Language; setLanguage: (language: Language) => void; t: Translate }

const I18nContext = createContext<I18nContextValue | null>(null)
const storageKey = 'godsend.language'

function storedLanguage(): Language {
  try { return localStorage.getItem(storageKey) === 'pt-BR' ? 'pt-BR' : 'en' }
  catch { return 'en' }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(storedLanguage)

  useEffect(() => {
    document.documentElement.lang = language
    try { localStorage.setItem(storageKey, language) } catch { /* Storage can be disabled. */ }
  }, [language])

  const value = useMemo<I18nContextValue>(() => ({
    language,
    setLanguage,
    t: (key, values) => (language === 'en' ? en[key] : ptBr[key]).replace(/\{(\w+)\}/g, (_, name: string) => String(values?.[name] ?? '')),
  }), [language])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error('I18nProvider is missing')
  return value
}
